// Builds @shamallya-ui/tokens: CSS variables (light, dark, auto), a Tailwind preset and resolved JSON.
// Source of truth: tokens/**/*.json (W3C DTCG format). Transformer: Style Dictionary (ADR-0001, ADR-0002).
import StyleDictionary from 'style-dictionary';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { combine, combineTheme, filesForMode, lintThemeRamps, loadFiles, resolveAll, validate, lintNames } from './lib/tokens.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'packages/tokens/dist');
const work = join(dist, '.work');
const rel = (...p) => join(root, ...p);

const SHARED = ['tokens/primitive/**/*.json', 'tokens/semantic/shared.json', 'tokens/component/**/*.json'];
const typeOf = (t) => t.$type ?? t.type;

// Tailwind preset: semantic colours/radius/shadow/z/fonts/motion as CSS variable references.
StyleDictionary.registerFormat({
  name: 'shamallya/tailwind-preset',
  format: ({ dictionary, options }) => {
    const v = (t) => `var(--${t.name})`;
    const colors = {};
    const put = (obj, keys, value) => {
      const last = keys.pop();
      let cur = obj;
      for (const k of keys) cur = cur[k] ??= {};
      cur[last === 'default' ? 'DEFAULT' : last] = value;
    };
    const maps = { spacing: {}, borderRadius: {}, boxShadow: {}, zIndex: {}, fontFamily: {}, fontSize: {}, transitionDuration: {}, transitionTimingFunction: {} };
    for (const t of dictionary.allTokens) {
      const [, tier, cat, ...rest] = t.path;
      if (tier === 'semantic' && cat === 'color') put(colors, [...rest], v(t));
      else if (tier === 'primitive' && cat === 'space') maps.spacing[rest.join('-')] = v(t);
      else if (tier === 'semantic' && cat === 'radius') maps.borderRadius[rest.join('-')] = v(t);
      else if (tier === 'semantic' && cat === 'shadow') maps.boxShadow[rest.join('-')] = v(t);
      else if (tier === 'semantic' && cat === 'z') maps.zIndex[rest.join('-')] = v(t);
      else if (tier === 'semantic' && cat === 'font') maps.fontFamily[rest.join('-')] = [v(t)];
      else if (tier === 'primitive' && cat === 'font' && rest[0] === 'size') maps.fontSize[rest.slice(1).join('-')] = v(t);
      else if (tier === 'semantic' && cat === 'motion' && rest[0].startsWith('transition-')) maps.transitionDuration[rest[0].replace('transition-', '')] = v(t);
      else if (tier === 'semantic' && cat === 'motion' && rest[0].startsWith('easing-')) maps.transitionTimingFunction[rest[0].replace('easing-', '')] = v(t);
    }
    const preset = { theme: { extend: { colors, ...maps } } };
    const body = JSON.stringify(preset, null, 2);
    const header = '// Generated by build/build.mjs from tokens/. Do not edit by hand.\n';
    return options.commonjs ? `${header}module.exports = ${body};\n` : `${header}export default ${body};\n`;
  },
});

StyleDictionary.registerFilter({ name: 'shamallya/size', filter: (t) => t.path[1] === 'semantic' && t.path[2] === 'size' });
StyleDictionary.registerFilter({ name: 'shamallya/themed-colour', filter: (t) => typeOf(t) === 'color' && t.path[1] !== 'primitive' });

const run = async (name, extraSource, platforms) => {
  const sd = new StyleDictionary({
    source: [...SHARED, ...extraSource].map((s) => rel(s)),
    log: { verbosity: 'silent', warnings: 'warn', errors: { brokenReferences: 'throw' } },
    platforms,
  });
  await sd.buildAllPlatforms();
  return name;
};

const files = (destination, format, extra = {}) => ({ destination, format, ...extra });

rmSync(dist, { recursive: true, force: true });
mkdirSync(work, { recursive: true });

await run('light', ['tokens/semantic/color-light.json', 'tokens/semantic/size-default.json'], {
  css: {
    transformGroup: 'css',
    buildPath: work + '/',
    files: [files('light.css', 'css/variables', { options: { selector: ':root', outputReferences: false } })],
  },
  tailwind: {
    transformGroup: 'css',
    buildPath: dist + '/',
    files: [
      files('tailwind-preset.js', 'shamallya/tailwind-preset', { options: { commonjs: false } }),
      files('tailwind-preset.cjs', 'shamallya/tailwind-preset', { options: { commonjs: true } }),
    ],
  },
});

await run('dark', ['tokens/semantic/color-dark.json'], {
  css: {
    transformGroup: 'css',
    buildPath: work + '/',
    files: [files('dark.css', 'css/variables', { filter: 'shamallya/themed-colour', options: { selector: ':root', outputReferences: false } })],
  },
});

await run('comfortable', ['tokens/semantic/color-light.json', 'tokens/semantic/size-comfortable.json'], {
  css: {
    transformGroup: 'css',
    buildPath: work + '/',
    files: [files('comfortable.css', 'css/variables', { filter: 'shamallya/size', options: { selector: ':root', outputReferences: false } })],
  },
});

// ---- Assemble tokens.css: light by default, dark by attribute or system preference ----
const declarations = (css) => css.split('\n').filter((l) => /^\s+--/.test(l));
const light = declarations(readFileSync(join(work, 'light.css'), 'utf8'));
const dark = declarations(readFileSync(join(work, 'dark.css'), 'utf8'));
const comfortable = declarations(readFileSync(join(work, 'comfortable.css'), 'utf8'));
const indent = (lines, n) => lines.map((l) => ' '.repeat(n) + l.trim()).join('\n');
const css = [
  '/* Generated by build/build.mjs from tokens/. Do not edit by hand. */',
  '/* Light is the default. Dark applies with data-theme="dark", or automatically when the system prefers dark and data-theme is not "light". */',
  ':root {',
  '  color-scheme: light;',
  light.join('\n'),
  '}',
  '',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  '    color-scheme: dark;',
  indent(dark, 4),
  '  }',
  '}',
  '',
  ':root[data-theme="dark"] {',
  '  color-scheme: dark;',
  indent(dark, 2),
  '}',
  '',
  '@media (prefers-reduced-motion: reduce) {',
  '  :root {',
  '    --shamallya-semantic-motion-transition-fast: 0.01ms;',
  '    --shamallya-semantic-motion-transition-base: 0.01ms;',
  '  }',
  '}',
  '',
  '/* Comfortable mode: larger controls and text. Apply data-density="comfortable" to the root or to any container. */',
  '[data-density="comfortable"] {',
  indent(comfortable, 2),
  '}',
  '',
].join('\n');
writeFileSync(join(dist, 'tokens.css'), css);

// ---- Resolved JSON (literal values per mode) for tests, tooling and the contrast check ----
const filesAll = loadFiles(root);
const modeSets = Object.fromEntries(['light', 'dark', 'comfortable'].map((m) => [m, combine(filesForMode(filesAll, m))]));
const check = (label, set, extra = []) => {
  const problems = [...set.errors, ...validate(set.tokens), ...lintNames(set.tokens), ...extra];
  if (problems.length) throw new Error(`Token problems in ${label}; run npm run lint:\n` + problems.join('\n'));
};
for (const [m, set] of Object.entries(modeSets)) check(m, set);
const toObject = (map) => Object.fromEntries([...map.entries()].sort(([a], [b]) => a.localeCompare(b)));
const resolved = Object.fromEntries(Object.entries(modeSets).map(([m, set]) => [m, toObject(resolveAll(set.tokens))]));

// ---- Brand themes: brand-level overrides only (themes/<name>/). Emits dist/themes/<name>.css ----
resolved.themes = {};
mkdirSync(join(dist, 'themes'), { recursive: true });
for (const name of readdirSync(rel('themes')).sort()) {
  const themeFiles = loadFiles(root, `themes/${name}`);
  const out = {};
  const decls = {};
  for (const mode of ['light', 'dark']) {
    const set = combineTheme(filesAll, themeFiles, mode);
    check(`theme ${name} ${mode}`, set, lintThemeRamps(combine(themeFiles).tokens));
    out[mode] = toObject(resolveAll(set.tokens));
    decls[mode] = set.overridden
      .filter((p) => p.startsWith('shamallya.semantic.color.') || (mode === 'light' && p.startsWith('shamallya.semantic.radius.')))
      .sort()
      .map((p) => `--${p.split('.').join('-')}: ${out[mode][p]};`);
  }
  resolved.themes[name] = out;
  const sel = `[data-brand="${name}"]`;
  writeFileSync(join(dist, 'themes', `${name}.css`), [
    `/* Generated by build/build.mjs from themes/${name}/. Do not edit by hand. */`,
    `/* Brand theme "${name}": set data-brand="${name}" on the root or any container. Load after tokens.css. */`,
    `${sel} {`,
    indent(decls.light, 2),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    `  ${sel}:not([data-theme="light"]) {`,
    indent(decls.dark, 4),
    '  }',
    '}',
    '',
    `${sel}[data-theme="dark"],`,
    `[data-theme="dark"] ${sel} {`,
    indent(decls.dark, 2),
    '}',
    '',
  ].join('\n'));
}
writeFileSync(join(dist, 'tokens.resolved.json'), JSON.stringify(resolved, null, 2) + '\n');

rmSync(work, { recursive: true, force: true });
console.log('built packages/tokens/dist: tokens.css, themes/*.css, tailwind-preset.js/.cjs, tokens.resolved.json');
